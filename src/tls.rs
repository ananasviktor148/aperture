//! Self-signed TLS material and access token management.
//!
//! WebCodecs requires a secure context, so the viewer is served over HTTPS even
//! on the LAN. The certificate is generated once per host/IP set and cached.

use std::path::{Path, PathBuf};

use anyhow::Context;

pub fn data_dir() -> PathBuf {
    std::env::var_os("LOCALAPPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(std::env::temp_dir)
        .join("aperture")
}

pub fn load_or_create_token(dir: &Path, override_token: Option<String>) -> anyhow::Result<String> {
    std::fs::create_dir_all(dir).context("create data dir")?;
    if let Some(token) = override_token {
        return Ok(token);
    }
    let path = dir.join("token.txt");
    if let Ok(existing) = std::fs::read_to_string(&path) {
        let token = existing.trim().to_string();
        if token.len() >= 16 {
            return Ok(token);
        }
    }
    let token = format!("{:032x}", rand::random::<u128>());
    std::fs::write(&path, &token).context("write token")?;
    Ok(token)
}

pub async fn load_or_create_tls(
    dir: &Path,
    hosts: &[String],
) -> anyhow::Result<axum_server::tls_rustls::RustlsConfig> {
    std::fs::create_dir_all(dir).context("create data dir")?;
    let cert_path = dir.join("cert.pem");
    let key_path = dir.join("key.pem");
    let hosts_path = dir.join("hosts.txt");
    let wants_hosts = hosts.join(",");
    // Version marker so a certificate generated by an older build is replaced.
    let wanted = format!("v2|{wants_hosts}");
    let current = std::fs::read_to_string(&hosts_path).unwrap_or_default();

    if cert_path.exists() && key_path.exists() && current.trim() == wanted {
        let cert = tokio::fs::read(&cert_path).await?;
        let key = tokio::fs::read(&key_path).await?;
        if let Ok(config) = axum_server::tls_rustls::RustlsConfig::from_pem(cert, key).await {
            return Ok(config);
        }
        tracing::warn!("cached certificate unusable, regenerating");
    }

    let mut params = rcgen::CertificateParams::new(hosts.to_vec())
        .context("build certificate parameters")?;
    params.distinguished_name = rcgen::DistinguishedName::new();
    params
        .distinguished_name
        .push(rcgen::DnType::CommonName, "Aperture local link");
    let key = rcgen::KeyPair::generate().context("generate certificate key")?;
    let cert = params.self_signed(&key).context("self-sign certificate")?;
    let cert_pem = cert.pem();
    let key_pem = key.serialize_pem();
    std::fs::write(&cert_path, &cert_pem)?;
    std::fs::write(&key_path, &key_pem)?;
    std::fs::write(&hosts_path, &wanted)?;

    axum_server::tls_rustls::RustlsConfig::from_pem(cert_pem.into_bytes(), key_pem.into_bytes())
        .await
        .context("load generated certificate")
}

/// Constant-time token comparison.
pub fn token_matches(expected: &str, provided: Option<&str>) -> bool {
    let Some(provided) = provided else { return false };
    if expected.len() != provided.len() {
        return false;
    }
    let mut diff = 0u8;
    for (a, b) in expected.bytes().zip(provided.bytes()) {
        diff |= a ^ b;
    }
    diff == 0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compares_tokens() {
        assert!(token_matches("abcd", Some("abcd")));
        assert!(!token_matches("abcd", Some("abce")));
        assert!(!token_matches("abcd", Some("abc")));
        assert!(!token_matches("abcd", None));
    }
}
